import { createHmac } from "node:crypto";
import { expect, test } from "@playwright/test";

test("synthetic admin signs in with TOTP, reloads, and signs out", async ({ page, baseURL }) => {
  test.skip(process.env.ADMIN_E2E_ENABLED !== "1", "Requires the disposable local admin browser environment.");
  if (baseURL !== "http://127.0.0.1:3102") throw new Error("Admin end-to-end tests require the isolated local server.");
  const password = process.env.ADMIN_E2E_PASSWORD;
  const secret = process.env.ADMIN_E2E_SECRET;
  if (!password || !secret) throw new Error("Synthetic admin test credentials are missing.");
  const counter = Buffer.alloc(8);
  counter.writeBigUInt64BE(BigInt(Math.floor(Date.now() / 30000)));
  const hash = createHmac("sha1", Buffer.from(secret, "ascii")).update(counter).digest();
  const offset = hash[hash.length - 1] & 0x0f;
  const otp = String((hash.readUInt32BE(offset) & 0x7fffffff) % 1000000).padStart(6, "0");
  await page.goto("/control/login");
  await page.getByLabel("Email").fill("admin@example.invalid");
  await page.getByLabel("Password").fill(password);
  await page.getByLabel("Authenticator code").fill(otp);
  const loginResponse = page.waitForResponse((response) => response.url().endsWith("/admin-session") && response.request().method() === "POST");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  const loginBody: unknown = await (await loginResponse).json();
  expect(Boolean(loginBody && typeof loginBody === "object" && "token" in loginBody)).toBe(false);
  const adminCookie = (await page.context().cookies()).find((cookie) => cookie.name === "sl_admin_session");
  expect(adminCookie?.httpOnly).toBe(true);
  expect(adminCookie?.sameSite).toBe("Strict");
  await expect(page.getByRole("heading", { name: "Command center" })).toBeVisible();
  await expect(page.getByText("Open reports", { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole("heading", { name: "Command center" })).toBeVisible();
  const rideControl = page.getByRole("article").filter({ hasText: "Allow drivers to post new rides." });
  await rideControl.getByRole("button", { name: "Pause" }).click();
  const dialog = page.getByRole("dialog");
  await dialog.getByLabel("Reason").fill("Synthetic maintenance test");
  await dialog.getByLabel(/Type rides.new_ride_creation_enabled to confirm/).fill("rides.new_ride_creation_enabled");
  await dialog.getByRole("button", { name: "Confirm change" }).click();
  await expect(rideControl.getByText("Status: Paused")).toBeVisible();
  await expect(page.getByText(/Paused: Allow drivers to post new rides/)).toBeVisible();
  await rideControl.getByText("Recent history").click();
  await expect(rideControl.getByText(/Enabled → Paused by Synthetic admin/)).toBeVisible();
  await rideControl.getByRole("button", { name: "Restore previous value" }).click();
  await dialog.getByLabel("Reason").fill("Synthetic test complete");
  await dialog.getByLabel(/Type rides.new_ride_creation_enabled to confirm/).fill("rides.new_ride_creation_enabled");
  await dialog.getByRole("button", { name: "Confirm change" }).click();
  await expect(rideControl.getByText("Status: Enabled")).toBeVisible();
  await page.getByRole("link", { name: "View audit log" }).click();
  await expect(page.getByRole("heading", { name: "Audit log" })).toBeVisible();
  await page.getByLabel("action", { exact: true }).fill("feature_flag_changed");
  await page.getByRole("button", { name: "Apply filters" }).click();
  await expect(page.getByRole("heading", { name: "feature_flag_changed" })).toHaveCount(2);
  await page.getByRole("link", { name: "← Overview" }).click();
  await page.getByRole("button", { name: "Sign out" }).click();
  await expect(page).toHaveURL(/\/control\/login$/);
  await page.goto("/control");
  await expect(page).toHaveURL(/\/control\/login$/);
});
